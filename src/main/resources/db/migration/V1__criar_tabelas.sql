-- =====================================================================
-- V1 - Estrutura do banco (espelha o DER do documento).
-- SQL compatível com H2 (modo PostgreSQL) e com PostgreSQL.
-- =====================================================================

-- Unidades da rede (matriz e filiais). Cada unidade tem estoque e cardápio próprios.
CREATE TABLE unidades (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(120) NOT NULL,
    cidade      VARCHAR(80)  NOT NULL,
    uf          VARCHAR(2)   NOT NULL,
    ativa       BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMP    NOT NULL
);

-- Usuários com perfil (role). CPF NÃO é coletado: nenhuma funcionalidade do sistema
-- precisa dele (LGPD - princípio da minimização).
CREATE TABLE usuarios (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                      VARCHAR(120) NOT NULL,
    email                     VARCHAR(150) NOT NULL,
    senha_hash                VARCHAR(100) NOT NULL,         -- BCrypt (nunca a senha pura)
    perfil                    VARCHAR(20)  NOT NULL,         -- CLIENTE, ATENDENTE, COZINHA, GERENTE, ADMIN
    unidade_id                BIGINT,                        -- funcionário vinculado a uma unidade
    consentimento_fidelidade  BOOLEAN      NOT NULL DEFAULT FALSE,
    data_consentimento        TIMESTAMP,                     -- registro do consentimento (LGPD)
    ativo                     BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em                 TIMESTAMP    NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT fk_usuarios_unidade FOREIGN KEY (unidade_id) REFERENCES unidades (id),
    CONSTRAINT ck_usuarios_perfil CHECK (perfil IN ('CLIENTE','ATENDENTE','COZINHA','GERENTE','ADMIN'))
);

-- Catálogo de produtos da rede (preço oficial fica AQUI, não vem do cliente).
CREATE TABLE produtos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(120)   NOT NULL,
    descricao   VARCHAR(255),
    categoria   VARCHAR(50)    NOT NULL,
    preco       NUMERIC(10,2)  NOT NULL,
    ativo       BOOLEAN        NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMP      NOT NULL,
    CONSTRAINT ck_produtos_preco CHECK (preco > 0)
);

-- Estoque por unidade: a existência da linha (unidade, produto) define o cardápio da unidade.
CREATE TABLE estoques (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id    BIGINT    NOT NULL,
    produto_id    BIGINT    NOT NULL,
    quantidade    INTEGER   NOT NULL,
    atualizado_em TIMESTAMP NOT NULL,
    CONSTRAINT uk_estoque_unidade_produto UNIQUE (unidade_id, produto_id),
    CONSTRAINT fk_estoques_unidade FOREIGN KEY (unidade_id) REFERENCES unidades (id),
    CONSTRAINT fk_estoques_produto FOREIGN KEY (produto_id) REFERENCES produtos (id),
    CONSTRAINT ck_estoques_quantidade CHECK (quantidade >= 0)
);

-- Histórico de entradas/saídas de estoque (rastreabilidade).
CREATE TABLE movimentacoes_estoque (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estoque_id  BIGINT       NOT NULL,
    tipo        VARCHAR(10)  NOT NULL,     -- ENTRADA / SAIDA
    quantidade  INTEGER      NOT NULL,
    motivo      VARCHAR(255) NOT NULL,
    usuario_id  BIGINT,
    criado_em   TIMESTAMP    NOT NULL,
    CONSTRAINT fk_mov_estoque FOREIGN KEY (estoque_id) REFERENCES estoques (id),
    CONSTRAINT fk_mov_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_mov_tipo CHECK (tipo IN ('ENTRADA','SAIDA')),
    CONSTRAINT ck_mov_quantidade CHECK (quantidade > 0)
);

-- Pedido: canal_pedido é OBRIGATÓRIO (multicanalidade como dado de domínio).
CREATE TABLE pedidos (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id          BIGINT,                 -- nulo em venda de balcão sem identificação
    criado_por_id       BIGINT        NOT NULL, -- quem registrou (cliente ou atendente)
    unidade_id          BIGINT        NOT NULL,
    canal_pedido        VARCHAR(10)   NOT NULL,
    status              VARCHAR(25)   NOT NULL,
    valor_total         NUMERIC(10,2) NOT NULL,
    chave_idempotencia  VARCHAR(64),
    criado_em           TIMESTAMP     NOT NULL,
    atualizado_em       TIMESTAMP     NOT NULL,
    CONSTRAINT fk_pedidos_cliente FOREIGN KEY (cliente_id) REFERENCES usuarios (id),
    CONSTRAINT fk_pedidos_criado_por FOREIGN KEY (criado_por_id) REFERENCES usuarios (id),
    CONSTRAINT fk_pedidos_unidade FOREIGN KEY (unidade_id) REFERENCES unidades (id),
    CONSTRAINT uk_pedidos_idempotencia UNIQUE (criado_por_id, chave_idempotencia),
    CONSTRAINT ck_pedidos_canal CHECK (canal_pedido IN ('APP','TOTEM','BALCAO','PICKUP','WEB')),
    CONSTRAINT ck_pedidos_status CHECK (status IN ('AGUARDANDO_PAGAMENTO','PAGO','EM_PREPARACAO','PRONTO','ENTREGUE','CANCELADO'))
);
CREATE INDEX idx_pedidos_canal ON pedidos (canal_pedido);
CREATE INDEX idx_pedidos_status ON pedidos (status);
CREATE INDEX idx_pedidos_unidade ON pedidos (unidade_id);

-- Itens do pedido: guarda o preço do momento da compra (histórico não muda se o preço mudar).
CREATE TABLE itens_pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT        NOT NULL,
    produto_id      BIGINT        NOT NULL,
    quantidade      INTEGER       NOT NULL,
    preco_unitario  NUMERIC(10,2) NOT NULL,
    subtotal        NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_itens_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id),
    CONSTRAINT fk_itens_produto FOREIGN KEY (produto_id) REFERENCES produtos (id),
    CONSTRAINT ck_itens_quantidade CHECK (quantidade > 0)
);

-- Pagamento DESACOPLADO do pedido: um pedido pode ter várias tentativas (recusada, aprovada...).
CREATE TABLE pagamentos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id         BIGINT        NOT NULL,
    metodo            VARCHAR(10)   NOT NULL,
    status            VARCHAR(12)   NOT NULL,
    valor             NUMERIC(10,2) NOT NULL,
    codigo_transacao  VARCHAR(60),
    mensagem_gateway  VARCHAR(255),
    criado_em         TIMESTAMP     NOT NULL,
    CONSTRAINT fk_pagamentos_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id),
    CONSTRAINT ck_pagamentos_metodo CHECK (metodo IN ('PIX','CREDITO','DEBITO')),
    CONSTRAINT ck_pagamentos_status CHECK (status IN ('APROVADO','RECUSADO','ERRO','ESTORNADO'))
);

-- Programa de fidelidade: extrato de pontos (saldo = soma dos pontos).
CREATE TABLE fidelidade_transacoes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT       NOT NULL,
    pedido_id   BIGINT,
    tipo        VARCHAR(10)  NOT NULL,      -- ACUMULO / RESGATE / ESTORNO
    pontos      INTEGER      NOT NULL,      -- positivo (acúmulo) ou negativo (resgate/estorno)
    descricao   VARCHAR(255) NOT NULL,
    criado_em   TIMESTAMP    NOT NULL,
    CONSTRAINT fk_fid_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT fk_fid_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id),
    CONSTRAINT ck_fid_tipo CHECK (tipo IN ('ACUMULO','RESGATE','ESTORNO'))
);

-- Log de auditoria de ações sensíveis (criação/cancelamento de pedido, status, pagamento, login...).
CREATE TABLE logs_auditoria (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   BIGINT,
    acao         VARCHAR(40)  NOT NULL,
    entidade     VARCHAR(40)  NOT NULL,
    entidade_id  BIGINT,
    detalhes     VARCHAR(500),
    criado_em    TIMESTAMP    NOT NULL
);
CREATE INDEX idx_auditoria_acao ON logs_auditoria (acao);
